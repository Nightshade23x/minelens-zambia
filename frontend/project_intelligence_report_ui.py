"""Streamlit interface for existing Project Intelligence records in Research Reports."""
from __future__ import annotations

import hashlib
import json
import re

import streamlit as st

from app.project_intelligence import load_catalog
from app.project_intelligence_report import (
    friendly_qualifier, generate_intelligence_profile_pdf,
    prepare_intelligence_profile,
)


@st.cache_data(show_spinner=False)
def get_intelligence_catalog():
    return load_catalog()


def render_profile_report_ui() -> None:
    st.caption(
        "Single-record research PDFs | USGS facility snapshots (2024) or "
        "verified project evidence (2024/2026)"
    )
    st.markdown(
        "Prepare a source-backed PDF for **one existing catalog entry**. "
        "Facilities and investment projects remain separate record types; "
        "no new facts are generated by Ollama."
    )
    try:
        catalog, warnings = get_intelligence_catalog()
    except (OSError, ValueError, KeyError, TypeError) as exc:
        st.error(f"Unable to load project intelligence records: {exc}")
        st.stop()
    for warning in warnings:
        st.warning(warning)
    records = {entry["id"]: entry for entry in catalog}
    if not records:
        st.info("No project or facility records are available.")
        st.stop()
    key = "minelens_profile_report_choice"
    if st.session_state.get(key) not in records:
        st.session_state[key] = next(iter(records))
    with st.sidebar:
        st.header("Profile report configuration")
        selected_id = st.selectbox(
            "Project or facility", options=list(records), key=key,
            format_func=lambda id_: f"{records[id_]['name']} — {records[id_]['kind']}"
        )
        selected = records[selected_id]
        default_title = f"MineLens | {selected['name']} Research Profile"[:110]
        report_title = st.text_input(
            "Report title", value=default_title, key=f"ml_title_{selected_id}",
            max_chars=110,
        )
        analyst_notes = st.text_area(
            "Analyst notes (optional)", max_chars=1200,
            placeholder="Optional personal notes, separately identified as unverified.",
            key=f"ml_notes_{selected_id}",
        )

    try:
        prepared = prepare_intelligence_profile(
            selected, report_title=report_title, analyst_notes=analyst_notes,
        )
    except ValueError as exc:
        st.error(str(exc))
        st.stop()
    st.subheader(selected["name"])
    st.caption(f"{selected['kind']} | Evidence/source year: {selected['publication_year']}")
    a, b, c = st.columns(3)
    a.metric("Record type", "USGS facility" if selected["kind"] == "USGS facility" else "Project evidence")
    b.metric("Reported capacity records", len(prepared["capacities"]))
    c.metric("Documentary claims", len(prepared["claims"]))

    preview, evidence, export = st.tabs(["Report preview", "Sources & limitations", "Generate PDF"])
    with preview:
        st.markdown("**Reported operator / developer**")
        st.write(", ".join(selected.get("operator") or []) or "Not established in source")
        st.markdown("**Commodity**")
        st.write(", ".join(selected.get("commodities") or []) or "Not established in source")
        st.markdown("**Province / district**")
        st.write(", ".join(filter(None, [selected.get("province"), selected.get("district")])) or "Not established in source")
        if prepared["kind"] == "USGS facility":
            st.markdown("**Source-reported status**")
            st.write(", ".join(selected.get("status") or []) or "Not established in source")
            st.markdown("**Recorded equity owners**")
            st.write(", ".join(selected.get("owners") or []) or "Not established in source")
            st.markdown("**Source-reported capacity records**")
            if prepared["capacities"]:
                for item in prepared["capacities"]:
                    st.write(
                        f"{item.get('commodity') or 'Unknown commodity'}: "
                        f"{item.get('capacity') if item.get('capacity') is not None else 'Not reported'} "
                        f"{item.get('capacity_unit') or '(unit not reported)'}"
                    )
            else:
                st.write("No annual capacity available in the selected source record.")
        else:
            st.markdown("**Verified claims**")
            for i, claim in enumerate(prepared["claims"], 1):
                with st.expander(f"[{i}] {claim.get('label') or claim.get('kind')} — {claim['value']}"):
                    st.write(f"Qualification: {friendly_qualifier(claim.get('qualifier'))}")
                    st.write(f"Source: {claim['source_title']} | pages: {claim['pages']}")
                    st.write(claim["excerpt"])
        st.caption("No inferred production totals, current status, or exact mine coordinates.")

    with evidence:
        st.write(selected["source_scope"])
        st.write("**Primary source:**", selected["source_title"])
        if selected.get("source_url", "").startswith(("https://", "http://")):
            st.markdown(f"[Open primary source]({selected['source_url']})")
        for url in selected.get("supporting_urls") or []:
            if url.startswith(("https://", "http://")):
                st.markdown(f"[Recorded supporting source]({url})")
        st.info(
            "USGS records are historical facility entries. Project claims are source-cited "
            "declarations or historical figures, not independently verified live facts. "
            "Capacity is not output and district matching is not site geolocation."
        )

    with export:
        st.subheader("Generate source-backed PDF")
        fingerprint = hashlib.sha256(json.dumps(selected, sort_keys=True, default=str).encode("utf-8")).hexdigest()
        options_key = (selected_id, report_title, analyst_notes, fingerprint)
        if st.button("Generate selected profile PDF", type="primary"):
            try:
                with st.spinner("Formatting sourced profile..."):
                    pdf = generate_intelligence_profile_pdf(
                        selected, report_title=report_title, analyst_notes=analyst_notes,
                    )
            except ImportError:
                st.error("ReportLab is missing. Install it with: python -m pip install -r requirements-report.txt")
            except (ValueError, KeyError, OSError, RuntimeError) as exc:
                st.error(f"Could not generate PDF: {exc}")
            else:
                st.session_state["minelens_profile_pdf"] = pdf
                st.session_state["minelens_profile_pdf_options"] = options_key
        if (st.session_state.get("minelens_profile_pdf") and
                st.session_state.get("minelens_profile_pdf_options") == options_key):
            slug = re.sub(r"[^a-z0-9]+", "_", selected["name"].lower()).strip("_")[:55] or "record"
            st.success("Source-backed profile PDF is ready.")
            st.download_button(
                "Download selected project/facility PDF",
                data=st.session_state["minelens_profile_pdf"],
                file_name=f"minelens_{slug}_profile.pdf",
                mime="application/pdf", use_container_width=True,
            )
        elif st.session_state.get("minelens_profile_pdf"):
            st.info("Selection or report options changed. Generate a fresh PDF.")
        st.caption("This PDF is based on stored source snapshots, not live operating data.")
