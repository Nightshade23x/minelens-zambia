"""Create downloadable source-cited project briefs without AI-generated facts."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import streamlit as st
from app.project_comparison_data import load_comparison
from app.research_report import generate_project_report_pdf, prepare_report

try:
    from frontend.styles.theme import apply_theme
except ImportError:
    apply_theme = None

st.set_page_config(page_title="Research Reports | MineLens Zambia", page_icon="📄", layout="wide")
if apply_theme is not None:
    apply_theme()

st.title("Mining Research Report Generator")
st.caption("Source-cited PDFs | Kansanshi, Lumwana and Mingomba | Evidence snapshot: 19 November 2026")
st.markdown(
    "Create a **downloadable mining project brief** from the same verified claims as "
    "the Project Comparison dashboard. No new costs, production statistics or project "
    "status claims are generated by the language model."
)

@st.cache_data(show_spinner=False)
def get_projects():
    return load_comparison()

try:
    projects = get_projects()
except (OSError, ValueError, KeyError) as exc:
    st.error(f"The source-checked project snapshot could not be loaded: {exc}")
    st.stop()

with st.sidebar:
    st.header("Report configuration")
    chosen = st.multiselect(
        "Projects", list(projects), default=list(projects),
        help="Choose one to three projects included in the verified local snapshot.",
    )
    report_title = st.text_input(
        "Report title", value="Zambia Mining | Project Research Brief", max_chars=110
    )
    analyst_notes = st.text_area(
        "Optional analyst notes", placeholder="Your own observations (clearly labelled as unverified)",
        max_chars=1200, height=105,
    )

if not chosen:
    st.info("Select at least one project to prepare a report.")
    st.stop()

try:
    prepared = prepare_report(
        projects, chosen, report_title=report_title, analyst_notes=analyst_notes,
    )
except (ValueError, KeyError) as exc:
    st.error(str(exc))
    st.stop()

metric_a, metric_b, metric_c = st.columns(3)
metric_a.metric("Projects", len(prepared["entries"]))
metric_b.metric("Cited claim entries", len(prepared["references"]))
metric_c.metric("CapEx source passages", 2 * len(prepared["entries"]))

preview_tab, evidence_tab, export_tab = st.tabs([
    "Report preview", "Evidence & qualifications", "Generate PDF",
])

def _display_money(value: str) -> str:
    # Prevent Streamlit Markdown from interpreting dollar amounts as math.
    return str(value).replace("$", r"\$")


with preview_tab:
    st.subheader("Planned report content")
    st.caption("The preview is based on the verified November 2026 source snapshot, not live project data.")
    for entry in prepared["entries"]:
        c1, c2 = entry["capex"]
        capacity = entry["capacity"]
        with st.expander(f"{entry['name']} - {entry['developer']}", expanded=True):
            st.write(f"**Commodity:** {entry['commodity']}")
            st.markdown("**Declaration CapEx:** " + _display_money(c1.value) + f" (p. {c1.pages})")
            st.markdown("**Annex CapEx:** " + _display_money(c2.value) + f" (pp. {c2.pages})")
            st.write("**Announced capacity or potential:** " + capacity.value)
            history = [c.value for c in entry["historical"]]
            st.write("**2024 historical output:** " + ("; ".join(history) if history else "Not established in this evidence"))
    st.info(
        "The PDF includes two comparison charts, project fact tables, an evidence register, "
        "page citations, source dates where recorded, and explicit limitations."
    )

with evidence_tab:
    st.subheader("Source limitations carried into the PDF")
    st.markdown(
        "- CapEx figures are **estimates**, not confirmed final costs.\n"
        "- Mingomba's annex says **more than $2.0B**, not exactly $2.0B.\n"
        "- Two passages from the **same country compact** are not independent confirmations.\n"
        "- Announced production capacity or potential is **not** measured historical output.\n"
        "- 2024 copper concentrate and copper cathode volumes must not be combined.\n"
        "- Conflicting project-status language in the 2026 report is **not** a verified live update."
    )
    for record in prepared["references"]:
        claim = record["claim"]
        with st.expander(f"[{record['n']}] {claim.project} | {claim.kind} | p. {claim.pages}"):
            st.write(f"**Source:** {claim.source_title}")
            st.write(f"**Document:** {claim.document}")
            st.markdown("**Reported:** " + _display_money(claim.value))
            st.caption(claim.excerpt)
            if claim.source_url:
                st.markdown(f"[Open source website]({claim.source_url})")
            else:
                st.caption("Local MineLens source; no external URL recorded.")

with export_tab:
    st.subheader("Build PDF")
    st.caption(
        "The source evidence is checked locally before generating the report. "
        "Any analyst notes will be explicitly labelled as unverified."
    )
    selection_key = (tuple(chosen), report_title, analyst_notes)
    if st.button("Generate source-cited PDF", type="primary"):
        try:
            with st.spinner("Formatting project brief..."):
                pdf = generate_project_report_pdf(
                    projects, chosen, report_title=report_title,
                    analyst_notes=analyst_notes,
                )
        except ImportError:
            st.error("PDF support is missing. Run: python -m pip install -r requirements-report.txt")
        except (ValueError, KeyError, OSError, RuntimeError) as exc:
            st.error(f"Report generation failed: {exc}")
        else:
            st.session_state["minelens_pdf_bytes"] = pdf
            st.session_state["minelens_pdf_options"] = selection_key
    if (
        st.session_state.get("minelens_pdf_bytes")
        and st.session_state.get("minelens_pdf_options") == selection_key
    ):
        st.success("PDF is ready.")
        st.download_button(
            "Download mining research brief (PDF)",
            data=st.session_state["minelens_pdf_bytes"],
            file_name="minelens_project_research_brief.pdf",
            mime="application/pdf",
            use_container_width=True,
        )
    elif st.session_state.get("minelens_pdf_bytes"):
        st.info("Report options changed. Generate a new PDF for the current selection.")
    st.caption(
        "Research snapshot only; not a live operational feed, final investment valuation "
        "or confirmation of current project status."
    )
